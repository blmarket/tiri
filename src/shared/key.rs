#[repr(C)]
pub struct key_event {
    /// Explicit dispatch target, observed without extending its lifetime.
    /// An empty handle uses the queue client; an expired explicit target must not fall back.
    pub client: ClientWeak,
    pub key: key_code,
    pub m: mouse_event,
    pub bytes: Option<Vec<u8>>,
}

impl key_event {
    pub fn new(key: key_code, m: mouse_event, bytes: Option<Vec<u8>>) -> Box<Self> {
        Box::new(Self {
            client: std::rc::Weak::new(),
            key,
            m,
            bytes,
        })
    }

    /// Retain the explicit client, or resolve the queue client only when no
    /// explicit target was supplied. Expiry must not redirect input.
    pub fn resolve_client(
        &self,
        fallback: impl FnOnce() -> Option<ClientRef>,
    ) -> Option<ClientRef> {
        if std::rc::Weak::ptr_eq(&self.client, &std::rc::Weak::new()) {
            fallback()
        } else {
            self.client.upgrade()
        }
    }

    pub fn metadata_snapshot(&self) -> Self {
        Self {
            client: self.client.clone(),
            key: self.key,
            m: self.m,
            bytes: None,
        }
    }

    pub fn bytes_ptr_len(&self) -> Option<&[u8]> {
        self.bytes.as_deref()
    }
}

#[repr(C)]
pub struct key_table {
    /// Stable numeric identity for mode-tree sections; never an address.
    pub(crate) identity: u64,
    pub name: std::ffi::CString,
    pub activity_time: SystemTime,
    pub key_bindings: key_bindings,
    pub default_key_bindings: key_bindings,
}

impl key_table {
    pub fn empty() -> Self {
        thread_local! { static NEXT: std::cell::Cell<u64> = const { std::cell::Cell::new(0) }; }
        let identity = NEXT.with(|next| {
            let id = next.get();
            assert!(id < (1_u64 << 62), "key table identity exhausted");
            next.set(id + 1);
            id
        });
        Self {
            identity,
            name: Default::default(),
            activity_time: UNIX_EPOCH,
            key_bindings: key_bindings::default(),
            default_key_bindings: key_bindings::default(),
        }
    }
}

/// Each table owns its map directly; bindings keep their stable allocations.
#[derive(Default)]
pub struct key_bindings {
    pub storage: std::collections::BTreeMap<key_code, Box<key_binding>>,
}

impl key_bindings {
    pub fn get(&self, key: key_code) -> Option<&key_binding> {
        self.storage.get(&key).map(Box::as_ref)
    }

    pub fn get_mut(&mut self, key: key_code) -> Option<&mut key_binding> {
        self.storage.get_mut(&key).map(Box::as_mut)
    }

    pub fn iter(&self) -> impl Iterator<Item = &key_binding> {
        self.storage.values().map(Box::as_ref)
    }

    pub fn insert(&mut self, binding: Box<key_binding>) {
        self.storage.insert(binding.key, binding);
    }

    pub fn remove(&mut self, key: key_code) -> Option<Box<key_binding>> {
        self.storage.remove(&key)
    }
}

pub struct key_binding {
    pub key: key_code,
    pub commands: std::rc::Rc<std::cell::RefCell<cmd_list>>,
    pub note: Option<std::ffi::CString>,
    pub tablename: Option<std::ffi::CString>,
    pub flags: ::core::ffi::c_int,
}

impl key_binding {
    /// Borrow the retained command list for the remaining legacy command APIs.
    pub fn cmdlist(&self) -> &std::rc::Rc<std::cell::RefCell<cmd_list>> {
        &self.commands
    }

    /// Release the binding borrow before queueing or calling code that can
    /// replace the binding or remove its table.
    pub fn command(&self) -> KeyBindingCommand {
        KeyBindingCommand {
            key: self.key,
            commands: std::rc::Rc::clone(&self.commands),
            flags: self.flags,
        }
    }
}

pub struct KeyBindingCommand {
    pub key: key_code,
    pub commands: std::rc::Rc<std::cell::RefCell<cmd_list>>,
    pub flags: ::core::ffi::c_int,
}

impl KeyBindingCommand {
    pub fn cmdlist(&self) -> &std::rc::Rc<std::cell::RefCell<cmd_list>> {
        &self.commands
    }
}

